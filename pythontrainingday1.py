#Accept 5 paper marks , rollno, name; and calculate total and percentage if percentage >=85, student can take admission else can't take admission.

class Student:
    # Constructor to accept name, rollno, and 5 paper marks
    def __init__(self, name, rollno, p1, p2, p3, p4, p5):
        self.name = name
        self.rollno = rollno
        self.p1 = p1
        self.p2 = p2
        self.p3 = p3
        self.p4 = p4
        self.p5 = p5
        self.total = 0
        self.percentage = 0.0

    def calculate_and_check(self):
        # Calculate total and percentage
        self.total = self.p1 + self.p2 + self.p3 + self.p4 + self.p5
        self.percentage = (self.total / 500) * 100

        print(f"\nStudent: {self.name} (Roll No: {self.rollno})")
        print(f"Total Marks: {self.total}/500")
        print(f"Percentage: {self.percentage}%")

        #check eligibility
        if self.percentage >= 85:
            print(f"{self.name} can take admission.")
        else:
            print(f"{self.name} can't take admission.")

# Accept user inputs
name = input("Enter Name: ")
rollno = input("Enter Roll No: ")
print("Enter marks for 5 papers (out of 100):")
p1 = float(input("Paper 1: "))
p2 = float(input("Paper 2: "))
p3 = float(input("Paper 3: "))
p4 = float(input("Paper 4: "))
p5 = float(input("Paper 5: "))

# Create object using constructor
s = Student(name, rollno, p1, p2, p3, p4, p5)

# Calculate and check admission
s.calculate_and_check()

