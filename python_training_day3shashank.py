import numpy as np

students = np.array([
    [85, 80, 70],  # Student 1
    [80, 55, 70],  # Student 2
    [85, 92, 88],  # Student 3
    [80, 90, 45],  # Student 4
    [72, 68, 75]   # Student 5
])

students

avg_marks = np.mean(students, axis=1)
print("average marks :",avg_marks)

topper = np.argmax(avg_marks)
print("topper :",topper)

failed_students = np.mean(avg_marks < 50)
print("failed students :",failed_students)

# Performance Report

for i, avg in enumerate(avg_marks):
    status = "Pass" if avg >= 50 else "Fail"
    print(f"Student {i+1}: Avg = {avg:.2f} | {status}")

